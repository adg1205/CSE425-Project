#Converting audio to lyrics
import os, glob, time
import pandas as pd
import whisper

# CHANGE THESE TWO:
DATASET_ROOT = "/content/drive/MyDrive/genres_original"   # contains 7 genre folders
OUT_ROOT     = "/content/drive/MyDrive/lyrics_generated"  # transcripts will be saved here

os.makedirs(OUT_ROOT, exist_ok=True)

# Load Whisper model (tiny/base/small are good starting points)
model = whisper.load_model("small")  # example usage is from Whisper docs [web:2]

rows = []
genre_dirs = sorted([d for d in glob.glob(os.path.join(DATASET_ROOT, "*")) if os.path.isdir(d)])

for genre_dir in genre_dirs:
    genre = os.path.basename(genre_dir)
    out_genre_dir = os.path.join(OUT_ROOT, genre)
    os.makedirs(out_genre_dir, exist_ok=True)

    wav_files = sorted(glob.glob(os.path.join(genre_dir, "*.wav")))
    print(f"Genre={genre} | files={len(wav_files)}")

    for wav_path in wav_files:
        track_id = os.path.splitext(os.path.basename(wav_path))[0]
        out_txt  = os.path.join(out_genre_dir, f"{track_id}.txt")

        # Resume-friendly: skip if already transcribed
        if os.path.exists(out_txt) and os.path.getsize(out_txt) > 0:
            rows.append([genre, track_id, wav_path, out_txt, "SKIPPED_EXISTING"])
            continue

        try:
            t0 = time.time()

            # Transcribe (Whisper returns dict with "text") [web:2]
            result = model.transcribe(wav_path, language="en")
            text = (result.get("text") or "").strip()

            with open(out_txt, "w", encoding="utf-8") as f:
                f.write(text + "\n")

            rows.append([genre, track_id, wav_path, out_txt, f"OK_{time.time()-t0:.1f}s"])
        except Exception as e:
            rows.append([genre, track_id, wav_path, out_txt, f"ERROR: {repr(e)}"])

# Save a manifest CSV for your pipeline
df = pd.DataFrame(rows, columns=["genre", "track_id", "audio_path", "lyrics_path", "status"])
manifest_path = os.path.join(OUT_ROOT, "lyrics_manifest.csv")
df.to_csv(manifest_path, index=False)
print("Saved:", manifest_path)
